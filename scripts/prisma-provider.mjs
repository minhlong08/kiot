// Writes apps/api/prisma/pg/schema.prisma: the SQLite-first schema with the Postgres provider.
// Used by the Docker image: `node scripts/prisma-provider.mjs && prisma generate/db push --schema prisma/pg/schema.prisma`.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../apps/api/prisma');
const src = fs.readFileSync(path.join(root, 'schema.prisma'), 'utf8');
const out = src
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"')
  .replace('output   = "../src/generated/prisma"', 'output   = "../../src/generated/prisma"');
if (out === src || !out.includes('postgresql')) throw new Error('prisma-provider: schema header not recognised');
fs.mkdirSync(path.join(root, 'pg'), { recursive: true });
fs.writeFileSync(path.join(root, 'pg', 'schema.prisma'), `// Generated by scripts/prisma-provider.mjs — do not edit.\n${out}`);
console.log('wrote prisma/pg/schema.prisma');
